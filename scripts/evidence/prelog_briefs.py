"""List the owner's Codex briefs (attachment files) and any local transcript that references each.

Usage (repository root):
    python3 -I scripts/evidence/prelog_briefs.py > docs/agent-sessions/00-pre-log-codex-briefs.md
"""

import datetime
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from recurring_instructions import GAME  # noqa: E402
from redact import redact  # noqa: E402

dirs = [os.path.expanduser("~/.codex/sessions"), os.path.expanduser("~/.codex/archived_sessions")]
logs = [f for d in dirs for f in glob.glob(os.path.join(d, "**", "*.jsonl"), recursive=True)]
blob = {f: open(f, errors="ignore").read() for f in logs}
rows = []
for p in glob.glob(os.path.expanduser("~/.codex/attachments/*/*.txt")):
    t = open(p, errors="ignore").read()
    if not GAME.search(t):
        continue
    aid = os.path.basename(os.path.dirname(p))
    d = datetime.date.fromtimestamp(os.path.getmtime(p))
    ids = sorted({m.group(1)[:8] for f, b in blob.items() if aid in b
                  for m in [re.search(r"([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})", os.path.basename(f))] if m})
    rows.append((d, aid[:8], redact(t.strip().splitlines()[0][:90]).replace("|", "/"), ", ".join(f"`{i}`" for i in ids) or "none found"))
rows.sort()
print("""# 00 — Codex briefs without a surviving work-session transcript

| Field | Value |
| --- | --- |
| Agent | Codex (desktop app) |
| Role | Owner's task briefs to the implementation agent |
| Session ID | Unknown for most rows. The briefs exist as attachment files, and no matching work-session transcript survives locally |
| Session URL | None |
| Source | Local only, not committed: `~/.codex/attachments/<id>/Pasted text.txt` |

These briefs are evidence of **what the owner instructed**. They are not evidence that a session ran or what it produced. The date is the attachment file's modification time. "Transcript referencing it" lists any local Codex transcript that mentions the attachment id. A Codex permission-check transcript can mention an attachment without being the work session. Their themes are counted in `docs/midterm/RECURRING_INSTRUCTIONS.md`.

Generated by `scripts/evidence/prelog_briefs.py`.

| Date | Attachment | First line of the brief | Transcript referencing it |
| --- | --- | --- | --- |""")
for r in rows:
    print(f"| {r[0]} | `{r[1]}` | {r[2]} | {r[3]} |")

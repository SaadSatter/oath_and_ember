// Generate packages/agent/src/route/mazeCheckpointData.ts (the Hedge Maze
// checkpoints for Situations B and C) from the committed live baseline trace.
//
//   node --import tsx scripts/midterm/derive-maze-checkpoints.ts          # write the data file
//   node --import tsx scripts/midterm/derive-maze-checkpoints.ts --check  # exit 1 if it differs
//
// Free and offline: it reads one committed trace, verifies its hash chain and
// SHA-256, and writes one TypeScript file. It runs no game and calls no model.

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { verifyTrace, type TraceLine } from "../../packages/agent/src/trace.js";
import { deriveCheckpoint, type MazeCheckpoint } from "../../packages/agent/src/route/mazeCheckpoints.js";
import { repoInfo } from "../../packages/agent/src/repo.js";

// Version 2 (2026-11-04): the S2-A v2 reference run, after the cow posts (ffbdecb).
// Version 1 used baseline-quest-S2-local-seed0-live/ (the game before ffbdecb).
const TRACE = "midterms/saadsatter/evidence/traces/baseline-quest-S2-local-seed0-v2/trace.jsonl";
// The cuts (docs/midterm/HEDGE_MAZE_SITUATIONS.md, "Choosing the cuts").
const CUTS = [
  { id: "S2-B", cutTick: 1197, description: "The guards are defeated and the dry hedge is burned. The cow still blocks the lane; the wolf still carries the key; the gate is shut and the chest unopened." },
  { id: "S2-C", cutTick: 1962, description: "The guards are defeated, the dry hedge is burned and the cow has been moved out of the lane. The wolf still carries the key; the gate is shut and the chest unopened." },
] as const;

const root = repoInfo().root;
const tracePath = existsSync(join(root, TRACE)) ? join(root, TRACE) : join(root, TRACE.replace("midterms/saadsatter/", ""));
const raw = readFileSync(tracePath);
const lines = raw.toString("utf8").trim().split("\n").map((l) => JSON.parse(l)) as TraceLine[];
verifyTrace(lines);
const summary = JSON.parse(readFileSync(join(tracePath, "../summary.json"), "utf8")) as { situation: string; seed: number; player: string; gitHash: string; startHash: string };
const source = { trace: TRACE, sha256: createHash("sha256").update(raw).digest("hex"), situation: "S2-local" as const, seed: summary.seed, player: summary.player, gitHash: summary.gitHash };
if (summary.situation !== "S2-local" || summary.seed !== 0) throw Error("Unexpected source trace.");

const checkpoints: MazeCheckpoint[] = CUTS.map((c) => ({ ...c, source, ...deriveCheckpoint(lines, c.cutTick) }));
const out = `// GENERATED by scripts/midterm/derive-maze-checkpoints.ts from the committed
// live baseline trace (${TRACE},
// sha256 ${source.sha256}). Do not edit by hand: the
// test re-derives this data from the trace and fails if it differs.
import type { MazeCheckpoint } from "./mazeCheckpoints.js";

export const MAZE_CHECKPOINTS: Readonly<Record<"S2-B" | "S2-C", MazeCheckpoint>> = Object.freeze(${JSON.stringify(Object.fromEntries(checkpoints.map((c) => [c.id, c])), null, 2)} as Record<"S2-B" | "S2-C", MazeCheckpoint>);
`;
const target = join(root, "packages/agent/src/route/mazeCheckpointData.ts");
if (process.argv.includes("--check")) {
  const same = existsSync(target) && readFileSync(target, "utf8") === out;
  console.log(same ? "mazeCheckpointData.ts matches the trace." : "mazeCheckpointData.ts DIFFERS from the trace.");
  process.exit(same ? 0 : 1);
}
writeFileSync(target, out);
for (const c of checkpoints)
  console.log(`${c.id}: cut at tick ${c.cutTick}; Sieg ${c.actions.sieg.length} actions, Coco ${c.actions.coco.length}; shortened ${c.shortened ? `${c.shortened.player} #${c.shortened.index} ${c.shortened.recordedTicks}→${c.shortened.ticks} ticks` : "none"}`);
